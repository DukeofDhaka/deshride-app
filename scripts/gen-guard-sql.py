#!/usr/bin/env python3
"""Generates supabase/migrations/0003_guard.sql, the server copy of the
contact guard in src/lib/contactGuard.ts. Keep the word lists and patterns
here in step with that file; both are checked against
src/test/fixtures/guard-cases.json (vitest and supabase/tests/run.sh).

Usage: python3 scripts/gen-guard-sql.py
"""
import unicodedata
from pathlib import Path

WORDS = {
    "zero": "0", "oh": "0", "one": "1", "two": "2", "three": "3", "four": "4", "five": "5",
    "six": "6", "seven": "7", "eight": "8", "nine": "9",
    "শূন্য": "0", "শুন্য": "0", "এক": "1", "দুই": "2", "তিন": "3", "চার": "4", "পাঁচ": "5",
    "পাচ": "5", "সাত": "7", "আট": "8",
    "ছয়": "6", "নয়": "9",
    "জিরো": "0", "টু": "2", "থ্রি": "3", "ফোর": "4", "ফাইভ": "5", "সিক্স": "6", "সেভেন": "7",
    "এইট": "8", "নাইন": "9", "ওয়ান": "1",
}

CONTACT = [
    r"(?:https?://)?(?:www\.)?(?:wa\.me|api\.whatsapp\.com|chat\.whatsapp\.com|t\.me|telegram\.me|m\.me|messenger\.com|viber\.com|invite\.viber\.com|imo\.im|facebook\.com|fb\.com|fb\.me|instagram\.com)(?:/[^\s]*)?",
    r"\y(?:whatsapp|viber|tg|imo)://[^\s]*",
    r"[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}",
    r"\y(?:whats\s?app|wa|imo|viber|telegram|messenger)\s+(?:me|koren|korun|kor|kore|te|e|number|no\.?|id)\y",
    "(?:হোয়াটসঅ্যাপ|হোয়াটস অ্যাপ|ইমো|ভাইবার|টেলিগ্রাম|মেসেঞ্জার)(?:ে|তে|এ)?\\s*(?:নক|কল|মেসেজ|যোগাযোগ|নম্বর|নাম্বার|আইডি)",
]

PAYMENT = [
    r"\y(?:bkash|b-kash|bikash|nagad|rocket|upay)\s+(?:me|you|him|her|it|kore|kor|koro|korun|kroben|diyen|den|dio|to me|send)\y",
    r"\y(?:bkash|b-kash|bikash|nagad|rocket|upay|cash)\y[^.!?\n]{0,20}\ydirect(?:ly)?\y",
    r"\ydirect(?:ly)?\y[^.!?\n]{0,20}\y(?:bkash|b-kash|bikash|nagad|rocket|upay|cash)\y",
    r"\ysend\s+(?:me\s+)?(?:the\s+)?(?:money|taka|tk|fare)\y",
    r"\y(?:pay|paying|give|giving|take|taking)\y[^.!?\n]{0,20}\ycash\y",
    r"\ycash\s+(?:only|payment|in hand|on arrival|e|dite|diben)\y",
    r"\y(?:in\s+)?advance\y",
    r"\ypersonal\s+(?:number|no\.?|account|bkash|nagad)\y",
    r"\ypay\s+(?:you|me|him|her)\s+directly\y",
    r"\y(?:off[\s-]?app|outside\s+(?:the\s+)?app|without\s+(?:the\s+)?app)\y",
    "বিকাশ\\s*(?:করে|করুন|কইরা|কইরেন|দিন|দেন|পাঠান)",
    "নগদে?\\s*(?:পাঠান|দিন|দেন|করে)",
    "ক্যাশ",
    "নগদ\\s*টাকা",
    "অগ্রিম",
    "সরাসরি\\s*(?:টাকা|পেমেন্ট|দিন)",
    "হাতে\\s*হাতে",
    "অ্যাপের\\s*বাইরে",
    "(?:পার্সোনাল|ব্যক্তিগত)\\s*(?:নম্বর|নাম্বার|বিকাশ|একাউন্ট)",
]

PHONE = r"(?:\+?[8৮]\s*[-()_./​‍]*\s*[0০]?\s*[-()_./​‍]*\s*[1১]|[0০]\s*[-()_./​‍]*\s*[1১]|\(?\+?[8৮]\)?\s*[-()_./​‍]*\s*[0০]?\s*[-()_./​‍]*\s*[1১])\s*[-()_./​‍]*\s*[0-9০-৯](?:\s*[-()_./​‍]*\s*[0-9০-৯]){8}"


def nfc(s: str) -> str:
    # Text is NFC-normalised before matching. Bangla য় (U+09DF) is a
    # composition exclusion, so NFC always gives the decomposed য + ় form.
    return unicodedata.normalize("NFC", s)


def q(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


words = {nfc(k): v for k, v in WORDS.items()}
alt = "|".join(sorted(words, key=len, reverse=True))
letter = r"[A-Za-zঀ-৿]"
token = rf"(?:[0-9০-৯]|(?<!{letter})(?:{alt})(?!{letter}))"
sep = r"[\s\-–—_.,/()+​‍]*"
run = rf"(\+?{token}(?:{sep}{token})+)"
cases = "\n".join(f"    when {q(k)} then '{v}'" for k, v in words.items())
contact = "".join(f"  out := regexp_replace(out, {q(nfc(c))}, '[HIDDEN]', 'gi');\n" for c in CONTACT)
payment = ",\n".join(f"    {q(nfc(p))}" for p in PAYMENT)

sql = f"""-- Contact guard, server side. Mirrors src/lib/contactGuard.ts so a modified
-- app can't skip it; both are checked against src/test/fixtures/guard-cases.json.
-- Generated by scripts/gen-guard-sql.py: edit that script, not this file.

create or replace function app.number_word_digit(w text) returns text
language sql immutable as $$
  select case lower(w)
{cases}
    else '' end
$$;

create or replace function app.run_digits(run text) returns text
language plpgsql immutable as $$
declare tok text; out text := '';
begin
  for tok in select (regexp_matches(run, {q('(' + token + ')')}, 'gi'))[1] loop
    if tok ~ '[0-9০-৯]' then
      out := out || translate(tok, '০১২৩৪৫৬৭৮৯', '0123456789');
    else
      out := out || app.number_word_digit(tok);
    end if;
  end loop;
  return out;
end $$;

-- Hides phone numbers written in digits, words, or a mix.
-- Returns {{"text": …, "hit": true|false}}.
create or replace function app.hide_phones(t text) returns jsonb
language plpgsql immutable as $$
declare run text; out text := t; hit boolean := false; before text;
begin
  for run in select (regexp_matches(t, {q(run)}, 'gi'))[1] loop
    if app.run_digits(run) ~ '(880|88)?01[3-9][0-9]{{8}}' then
      out := replace(out, run, '[HIDDEN]');
      hit := true;
    end if;
  end loop;
  before := out;
  out := regexp_replace(out, {q(PHONE)}, '[HIDDEN]', 'gi');
  return jsonb_build_object('text', out, 'hit', hit or out <> before);
end $$;

create or replace function app.hide_contact_routes(t text) returns jsonb
language plpgsql immutable as $$
declare out text := t;
begin
{contact}  return jsonb_build_object('text', out, 'hit', out <> t);
end $$;

create or replace function app.detect_off_app_payment(t text) returns boolean
language sql immutable as $$
  select normalize(t, NFC) ~* any (array[
{payment}
  ])
$$;

-- For notes, bios, seat-request notes and report notes.
create or replace function app.censor(t text) returns text
language sql immutable as $$
  select app.hide_contact_routes(app.hide_phones(normalize(t, NFC))->>'text')->>'text'
$$;

-- For chat. `history` is the sender's own recent messages in this chat,
-- oldest first, so a number typed a few digits at a time is still caught.
create or replace function app.guard_message(t text, history text[] default '{{}}') returns jsonb
language plpgsql immutable as $$
declare
  p jsonb := app.hide_phones(normalize(t, NFC));
  r jsonb := app.hide_contact_routes(p->>'text');
  out text := r->>'text';
  flags text[] := '{{}}';
  mine text;
  recent text := '';
  joined text;
  m text;
  h text;
  n int := coalesce(array_length(history, 1), 0);
begin
  if (p->>'hit')::boolean or (r->>'hit')::boolean then
    flags := array_append(flags, 'contact');
  end if;
  mine := app.run_digits(out);
  if mine <> '' and not (p->>'hit')::boolean then
    if n > 0 then
      foreach h in array history[greatest(1, n - 4):n] loop
        recent := recent || app.run_digits(normalize(h, NFC));
      end loop;
    end if;
    joined := recent || mine;
    m := substring(joined from '(?:880|88)?01[3-9][0-9]{{8}}');
    -- Only when the number is completed by this message.
    if m is not null and strpos(joined, m) + length(m) - 1 > length(recent) then
      out := regexp_replace(out, {q(run)}, '[HIDDEN]', 'gi');
      out := regexp_replace(out, '[0-9০-৯]', '[HIDDEN]', 'g');
      out := btrim(regexp_replace(out, '(\\[HIDDEN\\][[:space:].-]*)+', '[HIDDEN] ', 'g'));
      flags := array_append(flags, 'contact');
    end if;
  end if;
  if app.detect_off_app_payment(t) then
    flags := array_append(flags, 'payment');
  end if;
  return jsonb_build_object('text', out, 'flags', to_jsonb(flags));
end $$;
"""
Path(__file__).resolve().parent.parent.joinpath("supabase/migrations/0003_guard.sql").write_text(sql)
print("wrote supabase/migrations/0003_guard.sql")
