#!/usr/bin/env bash
# Joins every migration and the demo seed into one file, supabase/setup-all.sql,
# so a new Supabase project can be set up with a single paste into SQL Editor.
# Re-run after changing any migration or the seed; supabase/tests/run.sh fails
# if the committed file is out of date.
#   scripts/build-setup-sql.sh            writes supabase/setup-all.sql
#   scripts/build-setup-sql.sh --stdout   prints it instead (used by the tests)
set -euo pipefail
cd "$(dirname "$0")/.."

build() {
  echo "-- DeshRide: complete database setup in one file."
  echo "-- Paste all of it into Supabase → SQL Editor and press Run. Safe to run again."
  echo "-- Generated by scripts/build-setup-sql.sh from supabase/migrations/ and"
  echo "-- supabase/seed.sql: edit those, not this file."
  for f in supabase/migrations/*.sql supabase/seed.sql; do
    echo
    echo "-- ======================================================================"
    echo "-- $f"
    echo "-- ======================================================================"
    echo
    cat "$f"
  done
}

if [ "${1:-}" = "--stdout" ]; then
  build
else
  build > supabase/setup-all.sql
  echo "wrote supabase/setup-all.sql ($(wc -l < supabase/setup-all.sql) lines)"
fi
